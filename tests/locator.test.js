const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const script = fs.readFileSync('index.html','utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
const node = () => ({value:'',style:{},children:[],textContent:'',appendChild(n){this.children.push(n)},replaceChildren(){this.children=[]},focus(){this.focused=true},scrollIntoView(){},setAttribute(k,v){this[k]=v}});
function harness(fetch) {
 const elements={};
 const context=vm.createContext({URL,URLSearchParams,AbortController,setTimeout,clearTimeout,fetch,document:{getElementById(id){return elements[id] ||= node()},createElement:node}});
 vm.runInContext(script,context);
 return {elements,run:code=>vm.runInContext(code,context)};
}
(async()=>{
 let mode='success';let request;
 const h=harness(async url=>{request=url;if(mode==='failure')throw new Error('offline');return {ok:true,json:async()=>mode==='empty'?{}:{query:{pages:{1:{index:1,pageid:1,title:'Pousando no Amor',extract:'Série sul-coreana.'}}}}}});
 h.run("switchTab('locator')");
 assert.equal(h.elements.suggestionCards.children.length,6);
 h.run("showSuggestions('dramas')");
 assert.equal(h.elements.suggestionCards.children.length,4);
 assert.equal(h.elements.suggestDramas['aria-pressed'],'true');
 assert.equal(h.elements.suggestAll['aria-pressed'],'false');
 h.elements.suggestionCards.children[0].onclick();
 assert.equal(h.elements.titleInput.value,'Pousando no Amor');
 await new Promise(resolve=>setTimeout(resolve,0));
 h.run("document.getElementById('titleInput').value=''");
 await h.run('searchTitles()');
 assert.equal(h.elements.suggestionCards.children.length,6);
 assert.match(h.elements.searchStatus.textContent,/Escolha uma das sugestões/);
 h.run("document.getElementById('titleInput').value='Pousando no Amor'");
 await h.run('searchTitles()');
 assert.equal(new URL(request).searchParams.get('gsrsearch'),'Pousando no Amor');
 assert.equal(h.elements.titleResults.children.length,1);
 assert.equal(h.elements.titleResults.children[0].children[0].textContent,'Pousando no Amor');
 assert.equal(h.elements.searchLinks.children.length,4);
 mode='empty';await h.run('searchTitles()');
 assert.equal(h.elements.titleResults.children.length,0);
 assert.match(h.elements.searchStatus.textContent,/Nenhuma correspondência/);
 mode='failure';await h.run('searchTitles()');
 assert.equal(h.elements.searchBtn.disabled,false);
 assert.equal(h.elements.searchStatus.className,'alert-box error');
 assert.equal(h.elements.searchLinks.children.length,4);
 h.run("document.getElementById('foundUrl').value='https://youtube.com/watch?v=example';sendToDownloader()");
 assert.equal(h.elements.urlInput.value,'https://youtube.com/watch?v=example');
 assert.equal(h.elements.downloadSection.style.display,'block');
 assert.equal(h.elements.urlInput.focused,true);
 h.run("document.getElementById('foundUrl').value='javascript:alert(1)';sendToDownloader()");
 assert.equal(h.elements.urlInput.value,'https://youtube.com/watch?v=example');
 assert.match(h.elements.handoffStatus.textContent,/válido/);
 h.run("document.getElementById('titleInput').value='O grande arquimago que ninguem levava a serio'");
 await h.run('searchTitles()');
 assert(h.elements.titleResults.children.length >= 1);
 assert.equal(h.elements.searchStatus.className,'alert-box success');
 assert(h.elements.titleResults.children.some(card=>card.children[0].textContent==='O Grande Arquimago que Ninguém Levava a Sério'));
 const shortCard = h.elements.titleResults.children[0];
 const shortActions = shortCard.children.find(node => node.className === 'locator-links');
 assert(shortActions.children.some(link => link.href.includes('/pt/full-episodes/')));
 assert(shortActions.children.some(link => link.href.includes('/pt/episode/')));
 assert(shortActions.children.some(link => link.textContent === 'Ver lista dos 51 episódios ↗'));
 assert.equal(h.run("seriesDetails({url:'https://netshort.com/pt/episode/unknown-123'})"),null);
 h.run("showSuggestions('shorts')");
 assert.equal(h.elements.suggestionCards.children[0].children[0].textContent,'O Grande Arquimago que Ninguém Levava a Sério');
 assert.equal(h.run("findShortTitles('arquimago').length > 0"),true);
 const episodeBase = 'https://netshort.com/pt/episode/example-2108502039966322689';
 const ep = harness(async () => ({ok:true,json:async()=>({total:2,complete:true,episodes:[{number:2,url:episodeBase+'-ep-2'},{number:1,url:episodeBase},{number:3,url:'https://evil.test/'}]})}));
 ep.run("document.getElementById('epButton');document.getElementById('epStatus');document.getElementById('epList')");
 await ep.run("loadEpisodeLinks('"+episodeBase+"',document.getElementById('epButton'),document.getElementById('epStatus'),document.getElementById('epList'))");
 assert.equal(ep.elements.epList.children.length,2);
 assert.equal(ep.elements.epList.children[0].children[0].textContent,'Episódio 1');
 assert.equal(ep.elements.epList.children[1].children[1].value,episodeBase+'-ep-2');
 assert.match(ep.elements.epStatus.textContent,/Lista completa/);
 assert.equal(ep.elements.epButton.disabled,false);
 const broken = harness(async () => {throw new Error('offline')});
 await broken.run("loadEpisodeLinks('"+episodeBase+"',document.getElementById('epButton'),document.getElementById('epStatus'),document.getElementById('epList'))");
 assert.equal(broken.elements.epButton.disabled,false);
 assert.match(broken.elements.epStatus.textContent,/Não foi possível/);
 console.log('Locator checks passed: results, empty search, network errors, encoded query, link transfer, unsafe URL.');
})().catch(e=>{console.error(e);process.exit(1)});
